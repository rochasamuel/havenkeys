// Writes the extension's and Android's keyword constants from words.json
// (spec 2026-10-19-shared-field-words-design §3). `--check` writes nothing
// and exits 1 when a committed copy differs from what it would write.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "../..");
const DEFAULT_OUT = {
  ts: join(ROOT, "apps/extension/src/autofill/words.generated.ts"),
  kotlin: join(ROOT, "apps/android/app/src/main/kotlin/net/havenkeys/android/autofill/Words.kt"),
};
const HEADER = "// Generated by packages/field-words/generate.mjs from words.json. Do not edit.";

/** The classifiers' text rule (text.ts, TextMatch.kt); the fixture's vectors keep the three equal. */
export function normalize(raw) {
  if (!raw) return "";
  return raw
    .slice(0, 200)
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

/** `entry`'s value for `platform`, or undefined when it has none. */
function valueFor(entry, platform, isList) {
  if (isList) return entry.words ?? entry[platform];
  return typeof entry === "number" ? entry : entry[platform];
}

function validate(words) {
  for (const [name, entry] of Object.entries(words.lists ?? {})) {
    if (!/^[A-Z][A-Z0-9_]*$/.test(name)) throw new Error(`bad name: ${name}`);
    if (entry.raw) continue;
    for (const list of [entry.words, entry.extension, entry.android]) {
      for (const w of list ?? []) {
        if (normalize(w) !== w) throw new Error(`not normalized: ${name}: ${w}`);
      }
    }
  }
}

function render(words, platform) {
  const lists = Object.entries(words.lists ?? {})
    .map(([name, entry]) => [name, valueFor(entry, platform, true)])
    .filter(([, v]) => v !== undefined);
  const numbers = Object.entries(words.numbers ?? {})
    .map(([name, entry]) => [name, valueFor(entry, platform, false)])
    .filter(([, v]) => v !== undefined);
  if (platform === "extension") {
    return [
      HEADER,
      "",
      ...lists.map(([n, v]) => `export const ${n}: readonly string[] = ${JSON.stringify(v)};`),
      ...numbers.map(([n, v]) => `export const ${n} = ${v};`),
      "",
    ].join("\n");
  }
  const kt = (s) => `"${s.replace(/[\\"$]/g, (c) => `\\${c}`)}"`;
  return [
    HEADER,
    "package net.havenkeys.android.autofill",
    "",
    "@Suppress(\"MagicNumber\", \"MaxLineLength\")",
    "internal object Words {",
    ...lists.map(([n, v]) => `    val ${n}: List<String> = listOf(${v.map(kt).join(", ")})`),
    ...numbers.map(([n, v]) => `    const val ${n} = ${v}`),
    "}",
    "",
  ].join("\n");
}

function readOrEmpty(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return "";
  }
}

export function generate({ check = false, wordsPath = join(HERE, "words.json"), out = DEFAULT_OUT } = {}) {
  const words = JSON.parse(readFileSync(wordsPath, "utf8"));
  validate(words);
  const stale = [];
  for (const [platform, path] of [["extension", out.ts], ["android", out.kotlin]]) {
    const text = render(words, platform);
    if (readOrEmpty(path) === text) continue;
    if (check) stale.push(path);
    else writeFileSync(path, text);
  }
  return { stale };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { stale } = generate({ check: process.argv.includes("--check") });
  if (stale.length) {
    console.error(`Stale, run \`pnpm --filter @havenkeys/field-words generate\`:\n${stale.map((p) => `  ${relative(ROOT, p)}`).join("\n")}`);
    process.exit(1);
  }
}
